#!/usr/bin/env python3
"""Builds the files MCPassthrough.fx and the voxel core read, from VoxeLibre's texture folder:

    mcrl_atlas.png   1024 x 1024 RGBA: 64 x 64 slots of 16 x 16, slot s at ((s % 64) * 16, (s // 64) * 16);
                     generated textures first, then every 16 x 16n PNG by file name (first frame of strips)
    mcrl_atlas.txt   "<slot> <name>" per slot
    mcrl_blocks.txt  the block types (blocks.py) in the format vox::BlockRegistry::parse reads
    mcrl_steve.png   the player skin in the modern 64 x 64 layout

Usage: build_assets.py --textures <dir> --out <dir> [--skin <png>] [--sheet <png>]
Outputs are byte-identical for the same inputs. See docs/SHADER_CONTRACT.md and README.md next to this file.
"""

import argparse
import os
import re
import sys
from dataclasses import dataclass, field

import numpy as np
from PIL import Image, ImageDraw

# blocks.py sits next to this file; found even when Python does not put the script's folder on the path (-I).
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import blocks as block_defs  # noqa: E402

SLOT_SIZE = 16
ATLAS_COLUMNS = 64
ATLAS_SIZE = SLOT_SIZE * ATLAS_COLUMNS
MAX_SLOTS = ATLAS_COLUMNS * ATLAS_COLUMNS
# The shader's MCTYPES texture holds ids up to 256 * 128 - 1; id 0 is air.
MAX_BLOCK_ID = 256 * 128 - 1
# The shader draws block texels with alpha > 0.5 and skin texels with alpha >= 0.5: 128 and up as 8 bits.
OPAQUE_ALPHA = 128
# Mean HSV saturation below which a texture counts as greyscale (made to be tinted). VoxeLibre's tintable textures
# (grass top, oak and jungle leaves) are slightly warm greys at about 0.19; its coloured leaves start at about 0.32.
GREY_SATURATION = 0.25

BLOCKS_FILE_HEADER = (
	"# mcrl blocks v1\n"
	"# Generated by tools/assets/build_assets.py from tools/assets/blocks.py: do not edit (ids are list order).\n"
	"# top / side / bottom: slots in mcrl_atlas.png (-1: no texture, drawn in color); flags 0/1; tint_faces: bit 0\n"
	"# top, 1 side, 2 bottom (#ffffff when none); color: average opaque colour of the side texture, untinted.\n"
	"# id name top side bottom solid visible breakable tint_faces tint color\n"
)

# Minecraft's conversion of a legacy 64 x 32 skin: the left leg and arm are the right ones, each face mirrored
# horizontally. (source x, y, width, height, destination x, y)
LEGACY_LIMB_COPIES = [
	(4, 16, 4, 4, 20, 48),
	(8, 16, 4, 4, 24, 48),
	(0, 20, 4, 12, 24, 52),
	(4, 20, 4, 12, 20, 52),
	(8, 20, 4, 12, 16, 52),
	(12, 20, 4, 12, 28, 52),
	(44, 16, 4, 4, 36, 48),
	(48, 16, 4, 4, 40, 48),
	(40, 20, 4, 12, 40, 52),
	(44, 20, 4, 12, 36, 52),
	(48, 20, 4, 12, 32, 52),
	(52, 20, 4, 12, 44, 52),
]

# Steve's boxes as trace_steve() in MCPassthrough.fx draws them: name, skin corner uv0, width, height, depth.
STEVE_BOXES = [
	("head", (0, 0), 8, 8, 8),
	("body", (16, 16), 8, 12, 4),
	("right arm", (40, 16), 4, 12, 4),
	("left arm", (32, 48), 4, 12, 4),
	("right leg", (0, 16), 4, 12, 4),
	("left leg", (16, 48), 4, 12, 4),
]

BLOCK_NAME = re.compile(r"^[a-z0-9_]+$")


class AssetError(Exception):
	"""Unusable input: a missing texture, too many textures, an invalid block list or skin."""


@dataclass
class Atlas:
	pixels: np.ndarray
	# Texture name per slot (index = slot).
	names: list
	# The 16 x 16 RGBA image in each slot, by name.
	frames: dict
	generated: int = 0
	skipped_other: int = 0
	skipped_size: int = 0
	slots: dict = field(default_factory=dict)

	def slot(self, name):
		return self.slots[name]


@dataclass
class ResolvedBlock:
	id: int
	name: str
	top: int
	side: int
	bottom: int
	solid: bool
	visible: bool
	breakable: bool
	tint_faces: int
	tint: tuple
	color: tuple
	# (face, texture, saturation) of each requested tint the build dropped or kept.
	tints_dropped: list = field(default_factory=list)
	tints_kept: list = field(default_factory=list)


def load_rgba(path):
	"""An image file as an H x W x 4 uint8 array (palette and grey images expanded, transparency applied)."""
	try:
		with Image.open(path) as image:
			return np.array(image.convert("RGBA"), dtype=np.uint8)
	except (OSError, ValueError, SyntaxError) as e:
		raise AssetError(f"cannot read {path}: {e}") from e


def is_atlas_size(width, height):
	return width == SLOT_SIZE and height >= SLOT_SIZE and height % SLOT_SIZE == 0


def slot_origin(slot):
	"""Top-left pixel of an atlas slot."""
	return (slot % ATLAS_COLUMNS) * SLOT_SIZE, (slot // ATLAS_COLUMNS) * SLOT_SIZE


def first_frame(rgba, what):
	height, width = rgba.shape[:2]
	if not is_atlas_size(width, height):
		raise AssetError(f"{what} is {width} x {height}, not 16 x 16n")
	return rgba[:SLOT_SIZE, :SLOT_SIZE].copy()


def tint_rgba(rgba, rgb):
	"""Colour multiplied by `rgb` (as the shader tints: c * tint / 255), alpha kept."""
	out = rgba.copy()
	factor = np.array(rgb, dtype=np.uint32)
	out[..., :3] = ((rgba[..., :3].astype(np.uint32) * factor + 127) // 255).astype(np.uint8)
	return out


def composite_over(base, overlay):
	"""`overlay` drawn over `base` (Porter-Duff over, Minetest's "^"), rounded to 8 bits."""
	b = base.astype(np.float64) / 255.0
	o = overlay.astype(np.float64) / 255.0
	ao = o[..., 3:4]
	ab = b[..., 3:4] * (1.0 - ao)
	alpha = ao + ab
	rgb = (o[..., :3] * ao + b[..., :3] * ab) / np.maximum(alpha, 1e-12)
	rgb = np.where(alpha > 0.0, rgb, 0.0)
	out = np.concatenate([rgb, alpha], axis=-1)
	return np.floor(out * 255.0 + 0.5).astype(np.uint8)


def opaque_pixels(rgba):
	return rgba[..., :3][rgba[..., 3] >= OPAQUE_ALPHA]


def saturation(rgba):
	"""Mean HSV saturation of the texels the shader draws (0 when none are)."""
	rgb = opaque_pixels(rgba).astype(np.float64)
	if len(rgb) == 0:
		return 0.0
	high = rgb.max(axis=1)
	low = rgb.min(axis=1)
	sat = np.where(high > 0.0, (high - low) / np.maximum(high, 1.0), 0.0)
	return float(sat.mean())


def average_color(rgba, what):
	"""Average colour of the texels the shader draws, each channel rounded half up."""
	rgb = opaque_pixels(rgba).astype(np.int64)
	n = len(rgb)
	if n == 0:
		raise AssetError(f"{what} has no opaque texels to take a colour from")
	sums = rgb.sum(axis=0)
	return tuple(int((2 * s + n) // (2 * n)) for s in sums)


def hex_color(rgb):
	return "#{:02x}{:02x}{:02x}".format(*rgb)


def scan_textures(directory):
	"""Source textures for the atlas: (name, path) of each PNG in `directory` (not its subfolders) whose width is 16
	and height a positive multiple of 16, sorted by file name; and the counts of skipped entries (not a PNG file,
	other size)."""
	try:
		entries = sorted(os.listdir(directory))
	except OSError as e:
		raise AssetError(f"cannot list texture folder {directory}: {e}") from e
	sources = []
	skipped_other = 0
	skipped_size = 0
	for entry in entries:
		path = os.path.join(directory, entry)
		if not entry.lower().endswith(".png") or not os.path.isfile(path):
			skipped_other += 1
			continue
		try:
			with Image.open(path) as image:
				width, height = image.size
		except (OSError, ValueError, SyntaxError) as e:
			raise AssetError(f"cannot read {path}: {e}") from e
		if not is_atlas_size(width, height):
			skipped_size += 1
			continue
		sources.append((entry[:-4], path))
	return sources, skipped_other, skipped_size


def make_generated(recipe, directory):
	"""The 16 x 16 texture a blocks.Generated recipe describes."""
	frames = []
	for part in (recipe.base, recipe.overlay):
		path = os.path.join(directory, part + ".png")
		if not os.path.isfile(path):
			raise AssetError(f"generated texture {recipe.name} needs {part}.png, which is not in {directory}")
		frames.append(first_frame(load_rgba(path), f"{part}.png (for {recipe.name})"))
	base, overlay = frames
	if recipe.tint is not None:
		overlay = tint_rgba(overlay, recipe.tint)
	return composite_over(base, overlay)


def check_texture_name(name):
	if not name or any(c.isspace() for c in name):
		raise AssetError(f"texture name {name!r} cannot be written to mcrl_atlas.txt (empty or has whitespace)")


def build_atlas(directory, generated):
	"""Generated textures in slots 0..k-1 in list order, then the folder's textures by file name."""
	sources, skipped_other, skipped_size = scan_textures(directory)
	total = len(generated) + len(sources)
	if total > MAX_SLOTS:
		raise AssetError(f"{total} textures ({len(generated)} generated, {len(sources)} from {directory}) do not fit "
			f"the atlas's {MAX_SLOTS} slots")
	for recipe in generated:
		if not recipe.name.startswith("mcrl_"):
			raise AssetError(f"generated texture {recipe.name} must be named mcrl_...")

	pixels = np.zeros((ATLAS_SIZE, ATLAS_SIZE, 4), dtype=np.uint8)
	atlas = Atlas(pixels=pixels, names=[], frames={}, generated=len(generated), skipped_other=skipped_other,
		skipped_size=skipped_size)

	def place(name, frame):
		check_texture_name(name)
		if name in atlas.slots:
			raise AssetError(f"two textures are named {name}")
		slot = len(atlas.names)
		x, y = slot_origin(slot)
		pixels[y:y + SLOT_SIZE, x:x + SLOT_SIZE] = frame
		atlas.names.append(name)
		atlas.slots[name] = slot
		atlas.frames[name] = frame

	for recipe in generated:
		place(recipe.name, make_generated(recipe, directory))
	for name, path in sources:
		place(name, first_frame(load_rgba(path), path))
	return atlas


def resolve_blocks(block_list, atlas):
	"""Block types with atlas slots, tint decisions and colours; ids from 1 in list order."""
	if len(block_list) > MAX_BLOCK_ID:
		raise AssetError(f"{len(block_list)} blocks: ids above {MAX_BLOCK_ID} do not fit the shader's MCTYPES")
	missing = []
	seen = set()
	for block in block_list:
		if not BLOCK_NAME.match(block.name):
			raise AssetError(f"block name {block.name!r} must be lowercase letters, digits and underscores")
		if block.name in seen:
			raise AssetError(f"block name {block.name} is used twice")
		seen.add(block.name)
		if not isinstance(block.tint_faces, int) or not 0 <= block.tint_faces <= 7:
			raise AssetError(f"block {block.name}: tint_faces must be 0..7")
		for rgb in (block.tint, block.color):
			if rgb is not None and (len(rgb) != 3 or any(not isinstance(c, int) or not 0 <= c <= 255 for c in rgb)):
				raise AssetError(f"block {block.name}: colours must be three integers 0..255")
		for face, texture in (("top", block.top), ("side", block.side), ("bottom", block.bottom)):
			if texture is not None and texture not in atlas.slots:
				missing.append(f"{texture} ({block.name} {face})")
	if missing:
		raise AssetError("textures not in the atlas (no 16 x 16n PNG of that name in the texture folder, and not "
			"generated): " + ", ".join(missing))

	resolved = []
	for index, block in enumerate(block_list):
		faces = (("top", block_defs.TOP, block.top), ("side", block_defs.SIDE, block.side),
			("bottom", block_defs.BOTTOM, block.bottom))
		result = ResolvedBlock(id=index + 1, name=block.name,
			top=atlas.slot(block.top) if block.top is not None else -1,
			side=atlas.slot(block.side) if block.side is not None else -1,
			bottom=atlas.slot(block.bottom) if block.bottom is not None else -1,
			solid=block.solid, visible=block.visible, breakable=block.breakable, tint_faces=block.tint_faces,
			tint=tuple(block.tint), color=(0, 0, 0))
		# Never tint an already-coloured texture. A tinted face without a texture tints the block's colour: kept.
		for face, bit, texture in faces:
			if block.tint_faces & bit and texture is not None:
				sat = saturation(atlas.frames[texture])
				if sat >= GREY_SATURATION:
					result.tint_faces &= ~bit
					result.tints_dropped.append((face, texture, sat))
				else:
					result.tints_kept.append((face, texture, sat))
		if result.tint_faces == 0:
			result.tint = block_defs.WHITE
		if block.color is not None:
			result.color = tuple(block.color)
		elif block.side is not None:
			result.color = average_color(atlas.frames[block.side], f"{block.side} (side of {block.name})")
		else:
			raise AssetError(f"block {block.name} has no side texture and no color")
		resolved.append(result)
	return resolved


def format_blocks(resolved):
	lines = [BLOCKS_FILE_HEADER]
	for b in resolved:
		lines.append(f"{b.id} {b.name} {b.top} {b.side} {b.bottom} {int(b.solid)} {int(b.visible)} "
			f"{int(b.breakable)} {b.tint_faces} {hex_color(b.tint)} {hex_color(b.color)}\n")
	return "".join(lines)


def format_atlas_names(atlas):
	return "".join(f"{slot} {name}\n" for slot, name in enumerate(atlas.names))


def convert_skin(rgba):
	"""A skin in the modern 64 x 64 layout: a 64 x 64 skin as is; a legacy 64 x 32 one on top of a transparent
	bottom half, with the left limbs made from the right ones as Minecraft does."""
	height, width = rgba.shape[:2]
	if (width, height) == (64, 64):
		return rgba.copy()
	if (width, height) != (64, 32):
		raise AssetError(f"skin is {width} x {height}, not 64 x 32 or 64 x 64")
	out = np.zeros((64, 64, 4), dtype=np.uint8)
	out[:32] = rgba
	for sx, sy, w, h, dx, dy in LEGACY_LIMB_COPIES:
		out[dy:dy + h, dx:dx + w] = rgba[sy:sy + h, sx:sx + w][:, ::-1]
	return out


def steve_box_faces(uv0, width, height, depth):
	"""The skin rectangles (x, y, w, h) steve_box() samples for a box's faces: Minecraft's box layout."""
	u, v = uv0
	return {
		"top": (u + depth, v, width, depth),
		"bottom": (u + depth + width, v, width, depth),
		"right": (u, v + depth, depth, height),
		"front": (u + depth, v + depth, width, height),
		"left": (u + depth + width, v + depth, depth, height),
		"back": (u + 2 * depth + width, v + depth, width, height),
	}


def check_skin(skin):
	"""Faces of Steve's boxes where the shader would find see-through texels (it skips them: holes in Steve)."""
	problems = []
	for box, uv0, width, height, depth in STEVE_BOXES:
		for face, (x, y, w, h) in steve_box_faces(uv0, width, height, depth).items():
			holes = int(np.count_nonzero(skin[y:y + h, x:x + w, 3] < OPAQUE_ALPHA))
			if holes:
				problems.append(f"{box} {face}: {holes} of {w * h} texels see-through")
	return problems


def face_image(block, face, atlas):
	"""A block face as the shader colours it (before light): texture or flat colour, then the tint."""
	bit = {"top": block_defs.TOP, "side": block_defs.SIDE, "bottom": block_defs.BOTTOM}[face]
	slot = getattr(block, face)
	if slot >= 0:
		image = atlas.frames[atlas.names[slot]].copy()
	else:
		image = np.zeros((SLOT_SIZE, SLOT_SIZE, 4), dtype=np.uint8)
		image[..., :3] = block.color
		image[..., 3] = 255
	if block.tint_faces & bit:
		image = tint_rgba(image, block.tint)
	return image


def contact_sheet(resolved, atlas, scale=8, columns=4):
	"""Every block's top, side and bottom at `scale`, tinted as the shader tints, cutout texels on a checkerboard."""
	cell = SLOT_SIZE * scale
	gap = 4
	label = 16
	block_w = 3 * cell + 2 * gap
	pad = 24
	rows = (len(resolved) + columns - 1) // columns
	width = columns * block_w + (columns + 1) * pad
	height = rows * (cell + label + gap) + pad
	sheet = Image.new("RGB", (width, height), (40, 40, 40))
	draw = ImageDraw.Draw(sheet)
	checker = np.indices((cell, cell)).sum(axis=0) // (scale * 2) % 2
	background = np.where(checker[..., None] == 0, 170, 110).astype(np.uint8).repeat(3, axis=2)
	for i, block in enumerate(resolved):
		x0 = pad + (i % columns) * (block_w + pad)
		y0 = pad // 2 + (i // columns) * (cell + label + gap)
		draw.text((x0, y0), f"{block.id} {block.name}", fill=(255, 255, 255))
		for f, face in enumerate(("top", "side", "bottom")):
			image = face_image(block, face, atlas)
			big = image.repeat(scale, axis=0).repeat(scale, axis=1)
			visible = big[..., 3:4] >= OPAQUE_ALPHA
			rgb = np.where(visible, big[..., :3], background)
			sheet.paste(Image.fromarray(np.ascontiguousarray(rgb)), (x0 + f * (cell + gap), y0 + label))
	return sheet


def write_bytes(path, data):
	with open(path, "wb") as f:
		f.write(data)


def save_png(path, rgba):
	Image.fromarray(np.ascontiguousarray(rgba)).save(path, format="PNG")


def build(textures, out, skin=None, sheet=None, generated=None, block_list=None, log=print):
	"""Writes the four outputs into `out` (and the contact sheet to `sheet` if given). Raises AssetError."""
	generated = block_defs.GENERATED if generated is None else generated
	block_list = block_defs.BLOCKS if block_list is None else block_list
	skin = os.path.join(textures, "character.png") if skin is None else skin

	atlas = build_atlas(textures, generated)
	log(f"atlas: {atlas.generated} generated + {len(atlas.names) - atlas.generated} from {textures} = "
		f"{len(atlas.names)} of {MAX_SLOTS} slots")
	log(f"skipped: non-PNG entries {atlas.skipped_other}, PNGs not 16 x 16n {atlas.skipped_size}")

	resolved = resolve_blocks(block_list, atlas)
	log(f"blocks: {len(resolved)} (ids 1..{len(resolved)})")
	for b in resolved:
		for kept, entries in ((True, b.tints_kept), (False, b.tints_dropped)):
			faces_by_texture = {}
			for face, texture, sat in entries:
				faces_by_texture.setdefault((texture, sat), []).append(face)
			for (texture, sat), faces in faces_by_texture.items():
				what = f"{b.name} {'/'.join(faces)}: {texture}, saturation {sat:.2f}"
				log(f"  tinted {hex_color(b.tint)}  {what}" if kept else f"  not tinted (already coloured)  {what}")

	if not os.path.isfile(skin):
		raise AssetError(f"no skin at {skin}")
	steve = convert_skin(load_rgba(skin))
	problems = check_skin(steve)
	if problems:
		raise AssetError("the shader would draw holes in Steve: " + "; ".join(problems))
	log(f"skin: {skin} -> 64 x 64, every face the shader samples is opaque")

	os.makedirs(out, exist_ok=True)
	save_png(os.path.join(out, "mcrl_atlas.png"), atlas.pixels)
	write_bytes(os.path.join(out, "mcrl_atlas.txt"), format_atlas_names(atlas).encode("utf-8"))
	write_bytes(os.path.join(out, "mcrl_blocks.txt"), format_blocks(resolved).encode("utf-8"))
	save_png(os.path.join(out, "mcrl_steve.png"), steve)
	log(f"wrote mcrl_atlas.png, mcrl_atlas.txt, mcrl_blocks.txt, mcrl_steve.png to {out}")
	if sheet is not None:
		os.makedirs(os.path.dirname(os.path.abspath(sheet)), exist_ok=True)
		contact_sheet(resolved, atlas).save(sheet, format="PNG")
		log(f"wrote contact sheet {sheet}")
	return atlas, resolved, steve


def main(argv=None):
	parser = argparse.ArgumentParser(description="Build mcrl_atlas.png/.txt, mcrl_blocks.txt and mcrl_steve.png "
		"from a VoxeLibre texture folder.")
	parser.add_argument("--textures", required=True, help="folder of VoxeLibre PNGs (flat)")
	parser.add_argument("--out", required=True, help="output folder (the repo's assets/)")
	parser.add_argument("--skin", help="skin PNG, 64 x 32 or 64 x 64 (default: <textures>/character.png)")
	parser.add_argument("--sheet", help="also write a contact sheet of every block's faces to this PNG")
	args = parser.parse_args(argv)
	try:
		build(args.textures, args.out, skin=args.skin, sheet=args.sheet)
	except AssetError as e:
		print(f"error: {e}", file=sys.stderr)
		return 1
	return 0


if __name__ == "__main__":
	sys.exit(main())
